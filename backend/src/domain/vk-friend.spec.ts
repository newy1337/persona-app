import { asksVkFriend } from './vk-friend';

describe('просьба добавить в друзья ВК', () => {
  it.each([
    'добавь меня в друзья',
    'Добавь в друзья)',
    'добавьте в друзья пожалуйста',
    'кинь заявку в друзья',
    'прими заявку в друзья',
    'отправила тебе заявку в друзья',
    'я тебе заявку в друзья кинул',
    'в друзья добавь',
    'давай дружить, прими заявку в друзья',
    'Жду заявку в друзья',
  ])('ВК-чат: «%s» — да', (text) => {
    expect(asksVkFriend(text, 'vk')).toBe(true);
  });

  it.each([
    'у меня много друзей',
    'гуляли с друзьями вчера',
    'не добавляй меня в друзья',
    'добавь фото',
    'кинь фото, покажу друзьям',
    'скинь видео друзьям',
    'друзья говорят, что я весёлый',
    '',
  ])('ВК-чат: «%s» — нет', (text) => {
    expect(asksVkFriend(text, 'vk')).toBe(false);
  });

  it('в Telegram — только если речь о ВК', () => {
    expect(asksVkFriend('добавь в друзья', 'telegram')).toBe(false);
    expect(asksVkFriend('добавь меня в друзья в вк', 'telegram')).toBe(true);
    expect(asksVkFriend('кинь заявку в друзья ВКонтакте', 'telegram')).toBe(
      true,
    );
  });
});
