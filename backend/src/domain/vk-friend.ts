/**
 * Просьба добавить в друзья ВКонтакте: бот её выполнить не может (заявку
 * принимает или шлёт человек со страницы), поэтому чат уходит менеджеру.
 * В ВК-чате хватает слов о друзьях и заявке; в Telegram — только если
 * собеседник прямо говорит о ВК.
 */
const FRIEND =
  /(добав|кин|скин|отправ|прими|приня|кидай)\S*\s+(\S+\s+){0,3}?в\s+друз|заявк\S*\s+(\S+\s+){0,2}?(в\s+)?(друз|друж)|в\s+друз\S*\s+(\S+\s+){0,2}?(добав|кин|прими)/iu;
const NOT_REQUEST =
  /не\s+(добавля|добавлю|добавь|кидай|нужно|надо)\S*\s+(\S+\s+){0,2}?(в\s+)?друз/iu;
const MENTIONS_VK =
  /(^|[^a-zа-яё])(вк|vk|вконтакт\S*|контакт\S*)([^a-zа-яё]|$)/iu;

export function asksVkFriend(text: string, channel: string): boolean {
  const t = (text ?? '').replace(/\s+/g, ' ').trim();
  if (!t || !FRIEND.test(t) || NOT_REQUEST.test(t)) return false;
  return channel === 'vk' || MENTIONS_VK.test(t);
}

/** Как называем этот повод в очереди менеджера и в журнале. */
export const VK_FRIEND_PHRASE = 'просит добавить в друзья ВК';
