import { mentionsMedia } from './media-request';

describe('mentionsMedia', () => {
  it.each([
    'скинь фотку свою)',
    'а голосовое запишешь? хочу услышать твой голос',
    'давай кружочек',
    'покажи себя, а то вдруг ты бот',
    'пришлёшь фото кота?',
    'а как ты выглядишь?',
  ])('просьба «%s» — слова про медиа есть', (text) => {
    expect(mentionsMedia(text)).toBe(true);
  });

  it.each([
    'Договорились )',
    'Так что там по брату? Все хорошо?',
    'ну иногда нужно и замедлиться, отдохнуть',
  ])('«%s» — не просьба, слов про медиа нет', (text) => {
    expect(mentionsMedia(text)).toBe(false);
  });
});
